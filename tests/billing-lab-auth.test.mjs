import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import assert from "node:assert/strict";
const temp=fs.mkdtempSync(path.join(os.tmpdir(),"cvx-billing-lab-"));
let src=fs.readFileSync("backend/billing-lab-middleware.js","utf8");
const html=fs.readFileSync("backend/billing-lab-ui.html","utf8");
assert.equal((src.match(/__COMVERXA_LAB_HTML__/g)||[]).length,1);
src=src.replace("__COMVERXA_LAB_HTML__",JSON.stringify(html));
src=src.replace("/data/comverxa-billing-lab.sqlite",path.join(temp,"test.sqlite"));
const target=path.join(temp,"lab-unit.mjs");
fs.writeFileSync(target,src);
Bun.env.COMVERXA_BILLING_MODE="sandbox";
let captured, masterInvocations=0, unauthorized=0;
const originalBunServe=Bun.serve;
Bun.serve=options=>{captured=options.fetch;return {stop(){}};};
await import(target);
Bun.serve({fetch:async req=>{
 const route=new URL(req.url).pathname;
 if(route==="/api/master/me"){
  if(!(req.headers.get("cookie")||"").includes("csa_session=test"))return new Response("{}",{status:401});
  return Response.json({email:"owner@test.invalid",role:"master"});
 }
 if(route==="/api/master/overview")return Response.json({clients:[{id:"company_test",name:"Empresa Sandbox",customer_type:"mei",plan:"starter"}]});
 masterInvocations++;
 return new Response("unknown route",{status:404});
}});
const base="https://app.comverxa.com.br";
const cookie="csa_session=test";
const page=await captured(new Request(base+"/admin/billing-lab",{headers:{cookie}}));
assert.equal(page.status,200);
const setCookie=page.headers.get("set-cookie")||"";
assert.match(setCookie,/__Host-cvx-billing-csrf=[a-f0-9]{48}/);
assert.match(setCookie,/SameSite=Strict/);
assert.match(setCookie,/HttpOnly/);
const raw=await page.text();
const v=raw.match(/const BILLING_LAB_CSRF="([a-f0-9]{48})"/);
assert.ok(v,"CSRF token missing from authenticated page");
const csrf=v[1];
assert.ok(!raw.includes("BILLING_LAB_CSRF=__"));
const joinedCookies=cookie+"; "+setCookie.split(";")[0];
const payload={company_id:"company_test",reference:"2026-10",due_date:"2026-10-30",amount_cents:100};
async function post(route,obj,{origin="null",csrfHeader=csrf,cookies=joinedCookies,labHeader="sandbox",fetchSite}={}){
 const headers={"content-type":"application/json","cookie":cookies,"Origin":origin,"x-comverxa-billing-lab":labHeader};
 if(csrfHeader!==null)headers["x-comverxa-billing-csrf"]=csrfHeader;
 if(fetchSite)headers["sec-fetch-site"]=fetchSite;
 return captured(new Request(base+route,{method:"POST",headers,body:JSON.stringify(obj)}));
}
const unauthorizedRequest=await post("/api/master/billing-lab/invoices",payload,{cookies:""});
assert.equal(unauthorizedRequest.status,401);
const missingCsrf=await post("/api/master/billing-lab/invoices",payload,{csrfHeader:null});
assert.equal(missingCsrf.status,403);
const wrongCsrf=await post("/api/master/billing-lab/invoices",payload,{csrfHeader:"0".repeat(48)});
assert.equal(wrongCsrf.status,403);
const external=await post("/api/master/billing-lab/invoices",payload,{origin:"https://example.com"});
assert.equal(external.status,403);
const crossSite=await post("/api/master/billing-lab/invoices",payload,{fetchSite:"cross-site",origin:"https://attacker.example"});
assert.equal(crossSite.status,403);
const absentCookie=await post("/api/master/billing-lab/invoices",payload,{cookies:cookie});
assert.equal(absentCookie.status,403);
const good=await post("/api/master/billing-lab/invoices",payload,{fetchSite:"same-origin"});
assert.equal(good.status,201,await good.clone().text().catch(()=>""));
const saved=await good.json();
assert.equal(saved.realPayment,false);
assert.equal(saved.accessChanged,false);
assert.equal(saved.invoice.amount_cents,100);
// Railway forwards public HTTPS traffic to internal HTTP; protect by canonical origin,
// not the internal transport scheme. CSRF and admin session remain mandatory.
const proxyPayload={...payload,reference:"2026-12"};
const proxyHeaders={"Cookie":joinedCookies,"Origin":base,"Content-Type":"application/json","X-COMVERXA-Billing-Lab":"sandbox","X-COMVERXA-Billing-CSRF":csrf};
const proxyRequest=new Request("http://app.comverxa.com.br/api/master/billing-lab/invoices",{method:"POST",headers:proxyHeaders,body:JSON.stringify(proxyPayload)});
const proxyReply=await captured(proxyRequest);
assert.equal(proxyReply.status,201,await proxyReply.clone().text());
const opaqueCrossSite=await post("/api/master/billing-lab/mark-paid",{id:saved.invoice.id},{origin:"null",fetchSite:"cross-site"});
assert.equal(opaqueCrossSite.status,200,await opaqueCrossSite.clone().text());
const duplicate=await post("/api/master/billing-lab/invoices",payload);
assert.equal(duplicate.status,409);
const result=await opaqueCrossSite.json();
assert.equal(result.simulated,true);
assert.equal(result.paymentReceived,false);
assert.equal(result.crmAccessChanged,false);
const list=await captured(new Request(base+"/api/master/billing-lab/overview",{headers:{cookie}}));
assert.equal(list.status,200);
const data=await list.json();
assert.equal(data.invoices.find(x=>x.id===saved.invoice.id).status,"PAID_SIMULATED");
assert.equal(data.realChargesEnabled,false);
assert.equal(data.automaticAccessChanges,false);
// Renewal is manual and only allowed for a fictitiously paid competency.
const renewal=await post("/api/master/billing-lab/renew",{id:saved.invoice.id});
assert.equal(renewal.status,201,await renewal.clone().text());
const renewed=await renewal.json();
assert.equal(renewed.invoice.reference,"2026-11");
assert.equal(renewed.invoice.due_date,"2026-11-30");
assert.equal(renewed.invoice.status,"PENDING");
assert.equal(renewed.realCharge,false);
assert.equal(renewed.accessChanged,false);
assert.equal((await post("/api/master/billing-lab/renew",{id:saved.invoice.id})).status,409);
assert.equal((await post("/api/master/billing-lab/renew",{id:renewed.invoice.id})).status,409);
// Exercise overdue and imminent alerts independently of current runtime date.
const now=(await(await captured(new Request(base+"/api/master/billing-lab/overview",{headers:{cookie}}))).json()).today;
const near=new Date(Date.parse(now+"T00:00:00Z")+4*86400000).toISOString().slice(0,10);
const past=await post("/api/master/billing-lab/invoices",{...payload,reference:"2020-01",due_date:"2020-01-05"});
assert.equal(past.status,201);
const pastId=(await past.json()).invoice.id;
const future=await post("/api/master/billing-lab/invoices",{...payload,reference:"2020-02",due_date:near});
assert.equal(future.status,201);
const overview=await(await captured(new Request(base+"/api/master/billing-lab/overview",{headers:{cookie}}))).json();
assert.equal(overview.realChargesEnabled,false);
assert.equal(overview.automaticAccessChanges,false);
assert.equal(overview.remindersSent,false);
assert.equal(overview.alerts.overdue_count,1);
assert.equal(overview.alerts.overdue_cents,100);
assert.equal(overview.alerts.due_soon_count,1);
assert.equal(overview.alerts.due_soon_cents,100);
assert.equal(overview.alerts.aging.find(x=>x.key==="31_plus").count,1);
const reminder=await post("/api/master/billing-lab/remind",{id:pastId});
assert.equal(reminder.status,200,await reminder.clone().text());
assert.equal((await reminder.json()).emailSent,false);
assert.equal((await post("/api/master/billing-lab/remind",{id:pastId})).status,409);
assert.equal((await post("/api/master/billing-lab/remind",{id:pastId},{csrfHeader:null})).status,403);
const lastOverview=await(await captured(new Request(base+"/api/master/billing-lab/overview",{headers:{cookie}}))).json();
assert.ok(lastOverview.events.some(e=>e.event_type==="LEMBRETE_FICTICIO"));
assert.ok(lastOverview.events.some(e=>e.event_type==="RENOVACAO_FICTICIA"));
// 31 January becomes 29 February during leap years.
const leap=await post("/api/master/billing-lab/invoices",{...payload,reference:"2028-01",due_date:"2028-01-31"});
assert.equal(leap.status,201);
const leapId=(await leap.json()).invoice.id;
assert.equal((await post("/api/master/billing-lab/mark-paid",{id:leapId})).status,200);
const feb=await post("/api/master/billing-lab/renew",{id:leapId});
assert.equal(feb.status,201,await feb.clone().text());
const newInvoice=(await feb.json()).invoice;
assert.equal(newInvoice.reference,"2028-02");
assert.equal(newInvoice.due_date,"2028-02-29");
assert.equal(newInvoice.status,"PENDING");
assert.equal(masterInvocations,0,"Must not call CRM mutation routes");
console.log("PASS: admin-only renewal, month rollover, leap year, overdue aging, internal-only reminders and payment sandbox protections");
Bun.serve=originalBunServe;
fs.rmSync(temp,{recursive:true,force:true});
